using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;

namespace Transacto.Schemo;

internal sealed record BusinessTransactionModel(string FullyQualifiedName, bool IsAccessible);

internal static class BusinessTransactionJsonContextSource {
	public const string ContextName = "BusinessTransactionJsonContext";
	public const string RegistrationName = "BusinessTransactionJsonContextRegistration";

	private const string InterfaceNamespace = "Transacto.Domain";
	private const string InterfaceName = "IBusinessTransaction";

	public static BusinessTransactionModel? ToModel(GeneratorSyntaxContext context,
		CancellationToken cancellationToken) {
		if (context.SemanticModel.GetDeclaredSymbol(context.Node, cancellationToken) is not INamedTypeSymbol symbol) {
			return null;
		}

		if (symbol.TypeKind is not (TypeKind.Class or TypeKind.Struct) || symbol.IsAbstract || symbol.IsGenericType) {
			return null;
		}

		if (!ImplementsBusinessTransaction(symbol)) {
			return null;
		}

		return new BusinessTransactionModel(
			symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
			IsAccessibleFromNamespaceScope(symbol));
	}

	public static string GenerateContext(string @namespace, IEnumerable<string> typeNames) {
		var builder = new StringBuilder();

		builder.AppendLine("// <auto-generated/>");
		builder.AppendLine("using System.Runtime.CompilerServices;");
		builder.AppendLine("using System.Text.Json.Serialization;");
		builder.AppendLine();
		builder.Append("namespace ").Append(@namespace).AppendLine(";");
		builder.AppendLine();

		foreach (var typeName in typeNames) {
			builder.Append("[JsonSerializable(typeof(").Append(typeName).AppendLine("))]");
		}

		builder.Append("internal partial class ").Append(ContextName).AppendLine(" : JsonSerializerContext { }");
		builder.AppendLine();

		// Module initializers run before the first access to a type in this assembly, which is before any
		// code can read the shared options. Adding the resolver there keeps the options writable.
		builder.Append("internal static class ").Append(RegistrationName).AppendLine(" {");
		builder.AppendLine("\t[ModuleInitializer]");
		builder.AppendLine("\tinternal static void Register() =>");
		builder.Append("\t\tglobal::Transacto.TransactoSerializerOptions.Messages.TypeInfoResolverChain.Add(")
			.Append(ContextName).AppendLine(".Default);");
		builder.AppendLine("}");

		return builder.ToString();
	}

	private static bool ImplementsBusinessTransaction(INamedTypeSymbol symbol) =>
		symbol.AllInterfaces.Any(i => i.Name == InterfaceName &&
		                              i.ContainingNamespace.ToDisplayString() == InterfaceNamespace);

	// The generated context lives at namespace scope, so the type and every type containing it must be
	// visible from there.
	private static bool IsAccessibleFromNamespaceScope(INamedTypeSymbol symbol) {
		for (INamedTypeSymbol? current = symbol; current is not null; current = current.ContainingType) {
			if (current.IsGenericType) {
				return false;
			}

			if (current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal
				    or Accessibility.ProtectedOrInternal)) {
				return false;
			}
		}

		return true;
	}
}
