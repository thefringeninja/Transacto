using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Transacto;

[Generator]
public class LoggingScopeGenerator : IIncrementalGenerator {
	public void Initialize(IncrementalGeneratorInitializationContext context) {
		// Filter classes/structs with LoggingScopeAttribute
		var provider = context.SyntaxProvider
			.ForAttributeWithMetadataName(
				"Transacto.Framework.Logging.LoggingScopeAttribute",
				predicate: (node, _) => node is TypeDeclarationSyntax,
				transform: GetTypeToGenerate)
			.Where(t => t is not null);

		context.RegisterSourceOutput(provider, Execute!);
	}

	private static TypeToGenerate? GetTypeToGenerate(
		GeneratorAttributeSyntaxContext context,
		CancellationToken ct) {
		if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
			return null;

		var typeName = typeSymbol.Name;
		var namespaceName = typeSymbol.ContainingNamespace.IsGlobalNamespace
			? null
			: typeSymbol.ContainingNamespace.ToDisplayString();

		// Build the hierarchy of containing types (for nested types)
		var containingTypes = new List<ContainingTypeInfo>();
		var current = typeSymbol.ContainingType;
		while (current is not null) {
			var keyword = GetKeyword(current);

			containingTypes.Insert(0, new ContainingTypeInfo(current.Name, keyword));
			current = current.ContainingType;
		}

		// Get all public properties
		var properties = typeSymbol.GetMembers()
			.OfType<IPropertySymbol>()
			.Where(p => p is { DeclaredAccessibility: Accessibility.Public, IsStatic: false, IsIndexer: false })
			.Select(p => new PropertyInfo(p.Name, p.Type.ToDisplayString(), p.Type.IsValueType))
			.ToList();

		if (properties.Count == 0)
			return null;

		return new TypeToGenerate(
			typeName,
			namespaceName,
			GetKeyword(typeSymbol),
			properties,
			containingTypes);
	}

	private static string GetKeyword(INamedTypeSymbol current) {
		return current switch {
			{ TypeKind: TypeKind.Class, IsRecord: true } => "record",
			{ TypeKind: TypeKind.Struct, IsRecord: true } => "record struct",
			{ TypeKind: TypeKind.Struct } => "struct",
			_ => "class"
		};
	}

	private static void Execute(
		SourceProductionContext context,
		TypeToGenerate typeToGenerate) {
		var source = GenerateSource(typeToGenerate);
		context.AddSource($"{typeToGenerate.TypeName}.g.cs", SourceText.From(source, Encoding.UTF8));
	}

	private static string GenerateSource(TypeToGenerate type) {
		var sb = new StringBuilder();

		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable disable");
		sb.AppendLine();
		sb.AppendLine("using System.Collections;");
		sb.AppendLine("using System.Collections.Generic;");
		sb.AppendLine();

		if (type.Namespace is not null) {
			sb.AppendLine($"namespace {type.Namespace};");
			sb.AppendLine();
		}

		// Open containing type declarations
		foreach (var containingType in type.ContainingTypes) {
			sb.AppendLine($"partial {containingType.Keyword} {containingType.Name}");
			sb.AppendLine("{");
		}

		// Add indentation for nested types
		var indent = new string(' ', 4 * type.ContainingTypes.Count);

		sb.AppendLine(
			$"{indent}partial {type.Keyword} {type.TypeName} : IEnumerable<KeyValuePair<string, object>>");
		sb.AppendLine($"{indent}{{");

		// Generate GetEnumerator
		sb.AppendLine(
			$"{indent}    IEnumerator<KeyValuePair<string, object>> IEnumerable<KeyValuePair<string, object>>.GetEnumerator()");
		sb.AppendLine($"{indent}    {{");

		foreach (var prop in type.Properties) {
			// Handle nullable reference types and box value types
			sb.AppendLine(
				prop.IsValueType
					? $"{indent}        yield return new KeyValuePair<string, object>(nameof({prop.Name}), {prop.Name});"
					: $"{indent}        yield return new KeyValuePair<string, object>(nameof({prop.Name}), {prop.Name} ?? (object)\"null\");");
		}

		sb.AppendLine($"{indent}    }}");
		sb.AppendLine($"{indent}");

		// Generate non-generic GetEnumerator
		sb.AppendLine($"{indent}    IEnumerator IEnumerable.GetEnumerator()");
		sb.AppendLine($"{indent}    {{");
		sb.AppendLine($"{indent}        return ((IEnumerable<KeyValuePair<string, object>>)this).GetEnumerator();");
		sb.AppendLine($"{indent}    }}");

		sb.AppendLine($"{indent}}}");

		// Close containing type declarations
		for (int i = type.ContainingTypes.Count - 1; i >= 0; i--) {
			var closingIndent = new string(' ', 4 * i);
			sb.AppendLine($"{closingIndent}}}");
		}

		return sb.ToString();
	}

	private record TypeToGenerate(
		string TypeName,
		string? Namespace,
		string Keyword,
		List<PropertyInfo> Properties,
		List<ContainingTypeInfo> ContainingTypes);


	private record PropertyInfo(string Name, string Type, bool IsValueType);

	private record ContainingTypeInfo(string Name, string Keyword);
}
